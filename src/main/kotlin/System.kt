import java.io.File
import java.io.IOException

data class DeviceInfo(
    val name: String,
    val type: String,
    val driver: String?,
    val devPath: String?,
    val vendor: String? = null,
    val product: String? = null
)

data class SystemStats(
    val cpuModel: String,
    val cpuCores: Int,
    val memoryTotal: Long,
    val memoryFree: Long,
    val uptime: Long
)

/**
 * Read from /proc filesystem - kernel exposes runtime info here
 * This demonstrates direct file I/O with virtual files
 */
fun getCpuInfo(): Map<String, String> {
    val cpuInfo = mutableMapOf<String, String>()

    try {
        // /proc/cpuinfo is a virtual file generated by the kernel
        // It doesn't exist on disk - it's created when you read it
        File("/proc/cpuinfo").readLines().forEach { line ->
            if (line.contains(":")) {
                val (key, value) = line.split(":", limit = 2)
                cpuInfo[key.trim()] = value.trim()
            }
        }
    } catch (e: IOException) {
        println("Could not read /proc/cpuinfo: ${e.message}")
    }

    return cpuInfo
}

/**
 * Get system statistics from /proc
 * Shows how kernel exposes system state through virtual files
 */
fun getSystemStats(): SystemStats {
    var cpuModel = "Unknown"
    var cpuCores = 0
    var memoryTotal = 0L
    var memoryFree = 0L
    var uptime = 0L

    // CPU information
    val cpuInfo = getCpuInfo()
    cpuModel = cpuInfo["model name"] ?: "Unknown"
    cpuCores = cpuInfo["cpu cores"]?.toIntOrNull() ?: 0

    // Memory information from /proc/meminfo
    try {
        File("/proc/meminfo").readLines().forEach { line ->
            when {
                line.startsWith("MemTotal:") -> {
                    memoryTotal = line.split("\\s+".toRegex())[1].toLong() * 1024 // Convert KB to bytes
                }
                line.startsWith("MemFree:") -> {
                    memoryFree = line.split("\\s+".toRegex())[1].toLong() * 1024
                }
            }
        }
    } catch (e: IOException) {
        println("Could not read /proc/meminfo: ${e.message}")
    }

    // System uptime
    try {
        val uptimeStr = File("/proc/uptime").readText().trim()
        uptime = uptimeStr.split(" ")[0].toDouble().toLong()
    } catch (e: IOException) {
        println("Could not read /proc/uptime: ${e.message}")
    }

    return SystemStats(cpuModel, cpuCores, memoryTotal, memoryFree, uptime)
}